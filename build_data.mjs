// Bundles data/levels/*.json + data/text/content.json into src/generated/data.js
// so the game runs from file:// with zero fetch() calls, while the JSON files
// on disk stay the single editable source of truth (§9.4).
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './harness.mjs';

const levelsDir = path.join(ROOT, 'data', 'levels');
const contentPath = path.join(ROOT, 'data', 'text', 'content.json');
const outPath = path.join(ROOT, 'src', 'generated', 'data.js');

const content = JSON.parse(fs.readFileSync(contentPath, 'utf8'));
// 英文本地化：文件存在就一起打包，不存在就退回中文（英文模式会显示中文）
const enPath = path.join(ROOT, 'data', 'text', 'content.en.json');
const contentEn = fs.existsSync(enPath)
  ? JSON.parse(fs.readFileSync(enPath, 'utf8'))
  : content;
if (!fs.existsSync(enPath)) console.warn('[build_data] content.en.json 缺失，英文模式将回退中文');

const files = fs.readdirSync(levelsDir).filter((f) => f.endsWith('.json')).sort();
const levels = {};
let bytes = 0;
for (const f of files) {
  const raw = fs.readFileSync(path.join(levelsDir, f), 'utf8');
  bytes += raw.length;
  const id = f.replace(/\.json$/, '');
  levels[id] = JSON.parse(raw);
}

const lines = [];
lines.push('/* AUTO-GENERATED by tools/build_data.mjs — do not edit by hand.');
lines.push(' * 关卡与文本的唯一可编辑来源是 data/levels/*.json 与 data/text/content.json，');
lines.push(' * 本文件只是把它们打包成可直接被 file:// 页面加载的全局对象。 */');
lines.push('window.CT = window.CT || {};');
lines.push('CT.DATA = {');
lines.push('  content: ' + JSON.stringify(content) + ',');
lines.push('  text: { zh: ' + JSON.stringify(content) + ', en: ' + JSON.stringify(contentEn) + ' },');
lines.push('  levels: ' + JSON.stringify(levels) + ',');
lines.push('};');

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n') + '\n');

console.log(`bundled ${files.length} levels + content -> ${path.relative(ROOT, outPath)}`);
console.log(`source JSON ${(bytes / 1024).toFixed(1)} KB, bundle ${(fs.statSync(outPath).size / 1024).toFixed(1)} KB`);
