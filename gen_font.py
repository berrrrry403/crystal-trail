#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
晶途拾光 — 点阵字库生成器
=========================================================================
规格书 §7.5：字体为 8 × 8 像素点阵字，中文使用 12 × 12 点阵。

本脚本用系统字体在目标点阵尺寸下栅格化，再二值化到 1-bit，从而得到真正的
点阵字（无抗锯齿、无灰度）。输出为打包位图 + base64，写进
src/generated/font.js，运行时按需解位，不依赖任何图片解码能力。

用法:  python tools/gen_font.py
"""
import base64
import io
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = os.path.join(os.environ.get("WINDIR", r"C:\Windows"), "Fonts")
CJK_FONT = os.path.join(FONT_DIR, "simsun.ttc")
LAT_FONT = os.path.join(FONT_DIR, "lucon.ttf")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_JS = os.path.join(ROOT, "src", "generated", "font.js")
QA_DIR = os.path.join(ROOT, "build", "qa")

CJK_CELL = 12
LAT_CELL = 8
THRESHOLD = 110

# GB2312 全集：0xA1-0xA9 符号区（含，。、；：「」《》等全角标点）
# + 0xB0-0xF7 一、二级汉字（6763 字）。缺符号区会让对话里的全角标点变成缺字方框。
def gb2312_chars():
    out = []
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            out.append(ch)
    return out


# 游戏用到的拉丁与符号：ASCII 可打印区 + 少量全角标点（归入 CJK 表）
LAT_EXTRA = "×÷→←↑↓·—…‰°※★☆▲▼◆◇■□●○♪「」『』"


def build_font(path, size, cell, chars, index=0):
    """把每个字符栅格化到固定的 cell×cell 单元里，统一基线，绝不逐字居中。"""
    font = ImageFont.truetype(path, size, index=index)
    pad = 6
    canvas = cell + pad * 2

    # 第一遍：找出所有字的整体墨迹包围盒，据此决定统一的取样窗口。
    minx, miny, maxx, maxy = 10 ** 6, 10 ** 6, -10 ** 6, -10 ** 6
    raws = []
    for ch in chars:
        im = Image.new("L", (canvas, canvas), 0)
        d = ImageDraw.Draw(im)
        d.text((pad, pad), ch, font=font, fill=255)
        raws.append(im)
        bb = im.getbbox()
        if bb:
            minx = min(minx, bb[0]); miny = min(miny, bb[1])
            maxx = max(maxx, bb[2]); maxy = max(maxy, bb[3])
    if maxx < 0:
        raise SystemExit("no ink produced for font %s" % path)

    # 窗口：以墨迹包围盒为目标，尽量把整块墨迹放进 cell×cell，同时保证整数偏移
    win_x = minx - max(0, (cell - (maxx - minx)) // 2)
    win_y = miny - max(0, (cell - (maxy - miny)) // 2)
    win_x = max(0, min(win_x, canvas - cell))
    win_y = max(0, min(win_y, canvas - cell))

    clipped = 0
    glyphs = []
    for ch, im in zip(chars, raws):
        cellim = im.crop((win_x, win_y, win_x + cell, win_y + cell))
        if im.getbbox():
            bx0, by0, bx1, by1 = im.getbbox()
            if bx0 < win_x or by0 < win_y or bx1 > win_x + cell or by1 > win_y + cell:
                clipped += 1
        cellim = cellim.point(lambda v: 255 if v >= THRESHOLD else 0)
        glyphs.append(cellim)

    # 打包：每行按 MSB-first 比特串接
    bits = bytearray()
    acc = 0
    nbits = 0
    for g in glyphs:
        px = g.load()
        for y in range(cell):
            for x in range(cell):
                acc = (acc << 1) | (1 if px[x, y] else 0)
                nbits += 1
                if nbits == 8:
                    bits.append(acc & 0xFF)
                    acc = 0
                    nbits = 0
    if nbits:
        bits.append((acc << (8 - nbits)) & 0xFF)

    return {
        "cell": cell,
        "chars": "".join(chars),
        "bits": base64.b64encode(bytes(bits)).decode("ascii"),
        "clipped": clipped,
        "glyphs": glyphs,
    }


def main():
    if not os.path.exists(CJK_FONT):
        raise SystemExit("missing font: %s" % CJK_FONT)

    cjk_chars = gb2312_chars() + list(LAT_EXTRA)
    cjk = build_font(CJK_FONT, 12, CJK_CELL, cjk_chars, index=0)

    latin_chars = [chr(c) for c in range(32, 127)]
    lat = build_font(LAT_FONT, 8, LAT_CELL, latin_chars, index=0)

    # ---- QA 预览图：把两套字都排一遍，肉眼确认没有糊字 ----
    os.makedirs(QA_DIR, exist_ok=True)
    sample = "青藓初林拾光者 琥珀岩窟 云漫高台 碧泽水庭 星纹古殿 翠源晶暖珀晶流云晶澜光晶星核晶"
    line2 = "把左边那块反光石推到光路上 · 时序踏板 · 水流转向 · 符文拼图 · 藓藤蔓簇涟漪珊瑚"
    line3 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghijklmnopqrstuvwxyz 0123456789 !?.,:;%+-=/*()[]{} 60FPS 12/60"
    W = 12 * 30 + 4
    img = Image.new("RGB", (W, 12 * 2 + 10 * 2 + 12), (18, 16, 26))
    d = ImageDraw.Draw(img)
    cjk_font = ImageFont.truetype(CJK_FONT, 12, index=0)
    lat_font = ImageFont.truetype(LAT_FONT, 8)
    d.text((2, 2), sample, font=cjk_font, fill=(232, 240, 214))
    d.text((2, 18), line2, font=cjk_font, fill=(200, 214, 180))
    d.text((2, 34), line3, font=lat_font, fill=(255, 255, 255))
    img = img.point(lambda v: v)  # noop keeps API symmetric
    img.resize((W * 2, img.height * 2), Image.NEAREST).save(os.path.join(QA_DIR, "font-preview.png"))

    js = []
    js.append("/* AUTO-GENERATED by tools/gen_font.py — do not edit by hand.")
    js.append(" * 12x12 CJK (SimSun) + 8x8 Latin (Lucida Console), 1-bit packed, MSB-first.")
    js.append(" * 规格书 §7.5 点阵字规范。 */")
    js.append("window.CT = window.CT || {};")
    js.append("CT.FONT_DATA = {")
    for key, f in (("cjk", cjk), ("latin", lat)):
        js.append('  %s: {' % key)
        js.append("    cell: %d," % f["cell"])
        js.append("    chars: %s," % js_str(f["chars"]))
        js.append("    bits: %s" % js_str(f["bits"]))
        js.append("  },")
    js.append("};")
    os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
    with io.open(OUT_JS, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(js) + "\n")

    print("CJK glyphs: %d  cell %d  bytes %d  clipped %d" % (
        len(cjk_chars), CJK_CELL, len(cjk["bits"]) * 3 // 4, cjk["clipped"]))
    print("LAT glyphs: %d  cell %d  bytes %d  clipped %d" % (
        len(latin_chars), LAT_CELL, len(lat["bits"]) * 3 // 4, lat["clipped"]))
    print("wrote %s (%.1f KB)" % (OUT_JS, os.path.getsize(OUT_JS) / 1024.0))


def js_str(s):
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\u%04x" % o)
    out.append('"')
    return "".join(out)


if __name__ == "__main__":
    main()
